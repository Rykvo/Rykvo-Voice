  const codes = [...new Set(regions.map((region) => region.code))].sort(
    (a, b) => b.length - a.length,
  );
  function code(number) {
    const normalized = number.replace(/[\s()-]/g, "").replace(/^00/, "+");
    if (!/^\+\d+$/.test(normalized)) return "";
    return codes.find((value) => normalized.slice(1).startsWith(value)) || "";
  }
  function group(items) {
    const groups = new Map();
    for (const item of items) {
      const key = code(item.number);
      if (!groups.has(key)) groups.set(key, []);
      groups.get(key).push(item);
    }
    return [...groups].sort(
      ([a], [b]) => (a ? Number(a) : Infinity) - (b ? Number(b) : Infinity),
    );
  }
  function regionName(id) {
    return regions.find((region) => region.id === id)?.name || "";
  }
  function details(number, hint) {
    const raw = String(number)
      .replace(/[\s()-]/g, "")
      .replace(/^00/, "+");
    const callingCode = code(raw);
    if (!callingCode) {
      return /^1[3-9]\d{9}$/.test(raw)
        ? {
            national: raw,
            prefix: "",
            matches: regions.filter((item) => item.id === "CN"),
          }
        : null;
    }
    const national = raw.slice(callingCode.length + 1);
    const candidates = regions.filter((item) => item.code === callingCode);
    const selected = candidates.find((item) => item.id === hint);
    const matching = candidates.filter((item) => item.leading?.test(national));
    const fallback = candidates.filter((item) => !item.leading);
    return {
      national,
      prefix: `+${callingCode}`,
      matches: selected
        ? [selected]
        : matching.length
          ? matching
          : fallback.length
            ? fallback
            : candidates,
    };
  }
  function format(number, hint) {
    const info = details(number, hint);
    if (!info) return number;
    const { national, prefix, matches } = info;
    const plan = matches[0]?.groups || [];
    let parts;
    if (
      plan.length &&
      national.length <= plan.reduce((total, size) => total + size, 0)
    ) {
      let offset = 0;
      parts = plan.map((size) => {
        const part = national.slice(offset, offset + size);
        offset += size;
        return part;
      });
    } else {
      parts = national.match(/.{1,3}/g) || [];
    }
    return [prefix, ...parts].filter(Boolean).join(" ");
  }
  function country(number, hint) {
    const matches = details(number, hint)?.matches || [];
    return (
      matches
        .slice(0, 2)
        .map((item) => item.name)
        .join(" / ") + (matches.length > 2 ? "等" : "")
    );
  }
